import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const dir='public/assets/gkb-hero/';
const manifest=JSON.parse(await fs.readFile(`${dir}manifest.json`,'utf8'));
const originals=manifest.downloads.filter(a=>a.kind==='image'&&!a.variant);
const wanted=new Map(originals.map(a=>[a.sourceURL,a]));
const browser=await chromium.launch({headless:true,executablePath:'C:/Users/vikas/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const jobs=[];const captured=new Map();
page.on('response',r=>{
 const original=wanted.get(r.url());if(!original||captured.has(r.url()))return;
 captured.set(r.url(),true);
 jobs.push((async()=>{
  const type=r.headers()['content-type'];const ext={'image/webp':'webp','image/avif':'avif','image/png':'png','image/jpeg':'jpg'}[type];if(!ext)throw Error(type);
  const bytes=await r.body();
  const file=`/assets/gkb-hero/slide-${String(original.slide+1).padStart(2,'0')}-${original.viewport}-browser.${ext}`;
  await fs.writeFile(`public${file}`,bytes);
  const item={...original,file,contentType:type,bytes:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),variant:'browser-negotiated',requestAccept:r.request().headers().accept};
  manifest.downloads.push(item);
  const slide=manifest.slides[original.slide];slide[original.viewport]=file;
  console.log(file,type,bytes.length);
 })());
});
await page.goto('https://www.gkboptical.com/',{waitUntil:'domcontentloaded'});
await page.waitForSelector('.campaignSwiper',{state:'attached'});
await page.waitForTimeout(2000);
await page.locator('.campaignSwiper img').evaluateAll(imgs=>{for(const i of imgs)i.loading='eager';});
await page.waitForFunction(()=>[...document.querySelectorAll('.campaignSwiper img')].every(i=>i.complete&&i.naturalWidth>0),{timeout:30000});
await Promise.all(jobs);
for(const url of wanted.keys())if(!captured.has(url))throw Error(`Missing browser asset: ${url}`);
manifest.notes.push('Exact browser-negotiated WebP/AVIF response bodies are also preserved separately and used in the component; PNG/JPEG originals remain available.');
await fs.writeFile(`${dir}manifest.json`,JSON.stringify(manifest,null,2));
await browser.close();
